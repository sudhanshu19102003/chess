//! Converts the piece sprite sheet into `src/sprite_sheet.rs`, so the game
//! embeds the art as data and needs no image decoder at runtime.
//!
//!     cargo run --example import_sprites
//!
//! The sheet (assets/pieces/chess-pieces-static.png) is 6 columns of 16x16
//! sprites (rook, knight, bishop, queen, king, pawn) by 5 colour variants.
//! Row 0 is used for White and row 1 for Black.

use std::fmt::Write as _;

const SHEET: &str = concat!(env!("CARGO_MANIFEST_DIR"), "/../../assets/pieces/chess-pieces-static.png");
const OUT: &str = concat!(env!("CARGO_MANIFEST_DIR"), "/src/sprite_sheet.rs");
const CELL: usize = 16;
const KINDS: [&str; 6] = ["rook", "knight", "bishop", "queen", "king", "pawn"];
const ROWS: [(&str, usize); 2] = [("WHITE", 0), ("BLACK", 1)];
const KEYS: &[u8] = b"abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789";

fn main() {
    let decoder = png::Decoder::new(std::io::BufReader::new(std::fs::File::open(SHEET).expect(SHEET)));
    let mut reader = decoder.read_info().unwrap();
    let mut buf = vec![0; reader.output_buffer_size().unwrap()];
    let info = reader.next_frame(&mut buf).unwrap();
    assert_eq!(info.color_type, png::ColorType::Rgba, "expected an RGBA sheet");
    let (w, h) = (info.width as usize, info.height as usize);
    assert_eq!((w, h), (6 * CELL, 5 * CELL), "unexpected sheet size");
    let px = |x: usize, y: usize| {
        let i = (y * w + x) * 4;
        [buf[i], buf[i + 1], buf[i + 2], buf[i + 3]]
    };

    // One shared palette; fully transparent pixels become '.'.
    let mut palette: Vec<[u8; 4]> = Vec::new();
    let mut sprites = String::new();
    for (name, row) in ROWS {
        writeln!(sprites, "pub const {name}: [[&str; {CELL}]; 6] = [").unwrap();
        for (col, kind) in KINDS.iter().enumerate() {
            writeln!(sprites, "    // {kind}\n    [").unwrap();
            for y in 0..CELL {
                let mut line = String::new();
                for x in 0..CELL {
                    let c = px(col * CELL + x, row * CELL + y);
                    if c[3] == 0 {
                        line.push('.');
                        continue;
                    }
                    let i = palette.iter().position(|p| *p == c).unwrap_or_else(|| {
                        palette.push(c);
                        palette.len() - 1
                    });
                    line.push(KEYS[i] as char);
                }
                writeln!(sprites, "        \"{line}\",").unwrap();
            }
            writeln!(sprites, "    ],").unwrap();
        }
        writeln!(sprites, "];\n").unwrap();
    }
    assert!(palette.len() <= KEYS.len(), "too many colours");

    let mut out = String::new();
    writeln!(out, "//! Generated by `cargo run --example import_sprites` from").unwrap();
    writeln!(out, "//! assets/pieces/chess-pieces-static.png. Do not edit by hand.").unwrap();
    writeln!(out, "//!").unwrap();
    writeln!(out, "//! \"Chess Asset 16bit pixel art\" by Graciano Choc (gchoc / bz.gamedev), CC0 1.0.").unwrap();
    writeln!(out, "//! Pieces are in the order rook, knight, bishop, queen, king, pawn; each").unwrap();
    writeln!(out, "//! character indexes `PALETTE` (RGBA), and '.' is transparent.\n").unwrap();
    writeln!(out, "pub const SIZE: usize = {CELL};\n").unwrap();
    writeln!(out, "pub const KEYS: &[u8] = b\"{}\";\n", std::str::from_utf8(&KEYS[..palette.len()]).unwrap()).unwrap();
    writeln!(out, "pub const PALETTE: [[u8; 4]; {}] = [", palette.len()).unwrap();
    for c in &palette {
        writeln!(out, "    [{}, {}, {}, {}],", c[0], c[1], c[2], c[3]).unwrap();
    }
    writeln!(out, "];\n").unwrap();
    out.push_str(&sprites);
    std::fs::write(OUT, out.trim_end().to_string() + "\n").unwrap();
    println!("wrote {OUT}: {} colours", palette.len());
}
